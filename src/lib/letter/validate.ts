// Checks run on the final (possibly hand-edited) letter text before export.
// errors block export; warnings are shown but the citizen may continue.
import { LETTER_MAX_WORDS } from './compose.ts'

export type IssueCode =
  | 'missing_location'
  | 'missing_recipient'
  | 'missing_request'
  | 'placeholder'
  | 'ai_phrase'
  | 'url_in_body'
  | 'masked_token'
  | 'unretrieved_scheme'
  | 'eligibility_claim'
  | 'too_long'
  | 'missing_name'
  | 'official_voice'

export interface LetterIssue {
  code: IssueCode
  level: 'error' | 'warning'
  detail?: string
}

const PLACEHOLDER = /\[[^\]\n]{1,40}\]|<[A-Za-z ]{2,30}>|\b(insert|enter) (your |the )?(name|address|details|date)\b|\bX{3,}\b|_{4,}/i
const AI_PHRASES = /\b(here is (your|the) (letter|draft)|as an ai|language model|generated by (ai|chatgpt|gemini)|i hope this (letter )?helps|feel free to|certainly!|sure!)\b/i
const OFFICIAL_VOICE = /grievance cell|we have (registered|received) your complaint|dear citizen|on behalf of the corporation/i
const ELIGIBILITY = /\b(i am|we are) (eligible|entitled)\b|\bentitled to\b|\beligible for\b|\bqualif(y|ies) for\b|நான் தகுதியானவர்|உரிமை உள்ளது|मैं पात्र हूँ|मुझे .{0,20}का अधिकार है/i
const REQUEST = /\brequest\b|\bkindly\b|கேட்டுக்கொள்கிறேன்|வேண்டுகிறேன்|निवेदन|अनुरोध/i

export function wordCount(text: string): number {
  return text.split(/\s+/).filter(Boolean).length
}

export interface ValidateContext {
  location: string
  hasRecipient: boolean
  senderName?: string
  /** Knowledge-base scheme ids the citizen chose to cite. */
  allowedSchemeIds: number[]
}

export function validateLetter(text: string, ctx: ValidateContext): LetterIssue[] {
  const issues: LetterIssue[] = []
  if (!ctx.location.trim() || !text.includes(ctx.location.trim())) issues.push({ code: 'missing_location', level: 'error' })
  if (!ctx.hasRecipient) issues.push({ code: 'missing_recipient', level: 'error' })
  if (!REQUEST.test(text)) issues.push({ code: 'missing_request', level: 'error' })
  const ph = PLACEHOLDER.exec(text.replace(/\[(PHONE|ID|EMAIL)\]/g, ''))
  if (ph) issues.push({ code: 'placeholder', level: 'error', detail: ph[0] })
  const ai = AI_PHRASES.exec(text)
  if (ai) issues.push({ code: 'ai_phrase', level: 'error', detail: ai[0] })
  if (OFFICIAL_VOICE.test(text)) issues.push({ code: 'official_voice', level: 'error' })
  if (/https?:\/\//i.test(text)) issues.push({ code: 'url_in_body', level: 'error' })
  if (/\[(PHONE|ID|EMAIL)\]/.test(text)) issues.push({ code: 'masked_token', level: 'error' })
  for (const m of text.matchAll(/\bscheme (\d{1,3})\b|திட்டம் (\d{1,3})|योजना (\d{1,3})/gi)) {
    const id = Number(m[1] ?? m[2] ?? m[3])
    if (!ctx.allowedSchemeIds.includes(id)) issues.push({ code: 'unretrieved_scheme', level: 'error', detail: String(id) })
  }
  if (ELIGIBILITY.test(text)) issues.push({ code: 'eligibility_claim', level: 'error' })
  if (wordCount(text) > LETTER_MAX_WORDS) issues.push({ code: 'too_long', level: 'error', detail: String(wordCount(text)) })
  if (!ctx.senderName?.trim()) issues.push({ code: 'missing_name', level: 'warning' })
  return issues
}

export function blocking(issues: LetterIssue[]): boolean {
  return issues.some((i) => i.level === 'error')
}
