// Runs the fifteen acceptance complaints (page 35 of the knowledge base) through retrieve()
// with and without the precision fixes, and writes docs/ranking_before_after.md.
// Usage: npx tsx scripts/compare_ranking.ts
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { ACCEPTANCE } from '../eval/acceptance.ts'
import { LOCALITY_BOOST } from '../src/lib/config.ts'
import { embed } from '../src/lib/embed.ts'
import type { SchemeRecord } from '../src/lib/kb/types.ts'
import { retrieve, type Retrieved } from '../src/lib/rag/retrieve.ts'
import type { SearchIndex } from '../src/lib/search/rank.ts'

const K = 3
const records: SchemeRecord[] = JSON.parse(await readFile('public/data/schemes.json', 'utf8'))
const index: SearchIndex = JSON.parse(await readFile('public/data/index.json', 'utf8'))
const deps = { records, index, embed }
const flagged = records.filter((r) => r.self_excludes_city)

const cell = (h: Retrieved, withBoost: boolean) =>
  `#${h.record.id} ${h.record.name}${h.record.self_excludes_city ? ' ⚠️' : ''}<br>` +
  (withBoost ? `<sub>${h.score.toFixed(3)} + ${h.boost.toFixed(2)} = ${h.final.toFixed(3)}</sub>` : `<sub>${h.score.toFixed(3)}</sub>`)

// The bug report complaint first, then the fifteen acceptance complaints.
const complaints = [{ text: 'no water supply in Ward 12', schemes: [139, 83, 84] }, ...ACCEPTANCE]
const rows: string[] = []
let changed = 0
let removedSelfExcl = 0
for (const c of complaints) {
  const before = await retrieve(c.text, deps, { k: K, precisionFixes: false })
  const after = await retrieve(c.text, deps, { k: K, precisionFixes: true })
  const b = before.map((h) => h.record.id)
  const a = after.map((h) => h.record.id)
  if (b.join() !== a.join()) changed++
  removedSelfExcl += before.filter((h) => h.record.self_excludes_city).length
  const expected = c.schemes.length ? c.schemes.map((id) => `#${id}`).join(', ') : '—'
  rows.push(
    `| ${c.text} | ${expected} | ${before.map((h) => cell(h, false)).join('<br>')} | ${after.map((h) => cell(h, true)).join('<br>')} | ${b.join() === a.join() ? 'same' : 'changed'} |`,
  )
}

const md = `# Retrieval ranking: before and after the precision fixes

Generated by \`scripts/compare_ranking.ts\` on ${new Date().toISOString().slice(0, 10)}. Top ${K} from \`retrieve()\` for each complaint.

## The failure that prompted this

For the complaint **"no water supply in Ward 12"** (Chennai, urban) the system cited #17 Atal Bhujal Yojana. That record's own text says it is
"relevant to groundwater stress rather than routine city pipe complaints"; it matched only because "groundwater" is semantically close to "water".
Nothing was hallucinated (every number, name, page and URL was correct), so this was purely a ranking problem.

## The two fixes

1. **Self-exclusion filter.** Records whose \`what_it_does\` or \`matching_signals\` say they do not apply to ordinary city complaints are dropped for
   urban complaints (kept when the complaint mentions rural, village, panchayat, farm or agriculture). It matches a fixed phrase list only, so
   scheme-type clarifications such as "not a welfare scheme" (#84), "Not a scheme:" (#81) and "rather than benefit scheme" (#85) are not filtered.
   Flagged records (${flagged.length}): ${flagged.map((r) => `#${r.id}`).join(', ')}.
2. **Locality boost** (\`LOCALITY_BOOST\` in \`src/lib/config.ts\`), added to the cosine score for urban complaints: Chennai +${LOCALITY_BOOST.chennai},
   Tamil Nadu +${LOCALITY_BOOST.tamilNadu}, Urban/ULB +${LOCALITY_BOOST.urban}, otherwise +${LOCALITY_BOOST.other}. Results are ranked by the boosted score;
   the not-found threshold still uses the raw cosine score.

## Results

${changed} of ${complaints.length} complaints changed their top ${K}. Self-excluding records in the "before" top ${K}: ${removedSelfExcl}; after: 0.
⚠️ marks a record flagged \`self_excludes_city\`. "Expected" is the project's own routing expectation (\`eval/acceptance.ts\`), not part of the PDF.
Scores: before shows raw cosine; after shows raw + boost = final.

| Complaint | Expected | Before (raw cosine) | After (raw + boost = final) | Top ${K} |
|---|---|---|---|---|
${rows.join('\n')}

## Known limitation found by this comparison

For "no water supply in Ward 12" the fixes remove #17, but #84 Chennai Metropolitan Water Supply and Sewerage Board (the actual Chennai water
authority) still ranks 4th, behind #70 by a small margin. Its raw similarity to this complaint is low because its signals are phrased
"Water connection, sewer connection, leaks, sewer overflow, supply interruptions" rather than "no water supply". See the gate report for options;
the boost values were deliberately not tuned to force a pass.
`

await mkdir('docs', { recursive: true })
await writeFile('docs/ranking_before_after.md', md, 'utf8')
console.log(`Wrote docs/ranking_before_after.md (${changed}/${complaints.length} changed)`)
